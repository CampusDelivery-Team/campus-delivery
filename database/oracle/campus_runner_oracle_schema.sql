CREATE TABLE payments (
    payment_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    record_id       NUMBER NOT NULL,
    order_amount    NUMBER(10,2) NOT NULL,
    pay_amount      NUMBER(10,2) NOT NULL,
    pay_method      VARCHAR2(30 CHAR) NOT NULL,
    third_trade_no  VARCHAR2(100 CHAR),
    pay_status      VARCHAR2(20 CHAR) DEFAULT 'UNPAID' NOT NULL,
    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT fk_payments_record FOREIGN KEY (record_id)
        REFERENCES assign_records(record_id),
    CONSTRAINT uk_payments_trade_no UNIQUE (third_trade_no),
    CONSTRAINT ck_payments_order_amount CHECK (order_amount >= 0),
    CONSTRAINT ck_payments_pay_amount CHECK (pay_amount >= 0),
    CONSTRAINT ck_payments_method CHECK (pay_method IN ('WECHAT', 'ALIPAY', 'CASH')),
    CONSTRAINT ck_payments_status CHECK (pay_status IN ('UNPAID', 'PAID', 'FAILED', 'REFUNDED'))
);

COMMENT ON TABLE payments IS '围绕接派记录产生的支付记录';
COMMENT ON COLUMN payments.payment_id IS '支付编号，主键，身份列';
COMMENT ON COLUMN payments.record_id IS '接派记录编号，外键';
COMMENT ON COLUMN payments.order_amount IS '订单金额';
COMMENT ON COLUMN payments.pay_amount IS '实际支付金额';
COMMENT ON COLUMN payments.pay_method IS '支付方式：WECHAT/ALIPAY/CASH';
COMMENT ON COLUMN payments.third_trade_no IS '第三方交易流水号，唯一，可空';
COMMENT ON COLUMN payments.pay_status IS '支付状态：UNPAID/PAID/FAILED/REFUNDED';

CREATE TABLE refunds (
    refund_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    payment_id       NUMBER NOT NULL,
    refund_amount    NUMBER(10,2) NOT NULL,
    refund_reason    VARCHAR2(300 CHAR) NOT NULL,
    approved_amount  NUMBER(10,2),
    process_status   VARCHAR2(20 CHAR) DEFAULT 'APPLY' NOT NULL,
    CONSTRAINT pk_refunds PRIMARY KEY (refund_id),
    CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id)
        REFERENCES payments(payment_id),
    CONSTRAINT ck_refunds_amount CHECK (refund_amount >= 0),
    CONSTRAINT ck_refunds_approved CHECK (approved_amount IS NULL OR approved_amount >= 0),
    CONSTRAINT ck_refunds_status CHECK (process_status IN ('APPLY', 'APPROVED', 'REJECTED', 'DONE'))
);

COMMENT ON TABLE refunds IS '支付记录衍生的退款申请和处理信息';
COMMENT ON COLUMN refunds.refund_id IS '退款编号，主键，身份列';
COMMENT ON COLUMN refunds.payment_id IS '支付编号，外键';
COMMENT ON COLUMN refunds.refund_amount IS '申请退款金额';
COMMENT ON COLUMN refunds.refund_reason IS '申请原因';
COMMENT ON COLUMN refunds.approved_amount IS '核定金额';
COMMENT ON COLUMN refunds.process_status IS '处理状态：APPLY/APPROVED/REJECTED/DONE';

