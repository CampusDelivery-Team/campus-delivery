/* =========================
   4. 任务主单与三类任务明细表
   ========================= */
CREATE TABLE tasks (
    task_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    publisher_user_id  NUMBER NOT NULL,
    service_type_id    NUMBER NOT NULL,
    address_no         NUMBER NOT NULL,
    node_id            NUMBER NOT NULL,
    task_title         VARCHAR2(100 CHAR) NOT NULL,
    task_price         NUMBER(10,2) NOT NULL,
    urgent_flag        CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    task_status        VARCHAR2(30 CHAR) DEFAULT 'CREATED' NOT NULL,
    created_at         DATE DEFAULT SYSDATE NOT NULL,
    completed_at       DATE,
    CONSTRAINT pk_tasks PRIMARY KEY (task_id),
    CONSTRAINT fk_tasks_user FOREIGN KEY (publisher_user_id)
        REFERENCES users(user_id),
    CONSTRAINT fk_tasks_service FOREIGN KEY (service_type_id)
        REFERENCES service_types(service_type_id),
    CONSTRAINT fk_tasks_address FOREIGN KEY (publisher_user_id, address_no)
        REFERENCES user_addresses(user_id, address_no),
    CONSTRAINT fk_tasks_node FOREIGN KEY (node_id)
        REFERENCES nodes(node_id),
    CONSTRAINT fk_tasks_service_node FOREIGN KEY (service_type_id, node_id)
        REFERENCES service_node_rules(service_type_id, node_id),
    CONSTRAINT ck_tasks_price CHECK (task_price >= 0),
    CONSTRAINT ck_tasks_urgent CHECK (urgent_flag IN ('Y', 'N')),
    CONSTRAINT ck_tasks_status CHECK (task_status IN (
        'CREATED', 'PAID', 'WAITING', 'ASSIGNED', 'PICKED_UP',
        'DELIVERING', 'WAIT_CONFIRM', 'FINISHED', 'CANCELLED', 'REFUNDING'
    )),
    CONSTRAINT ck_tasks_time CHECK (completed_at IS NULL OR completed_at >= created_at)
);

COMMENT ON TABLE tasks IS '任务主单公共字段，关联发布用户、服务类型、地址和交接节点';
COMMENT ON COLUMN tasks.task_id IS '任务编号，主键，身份列';
COMMENT ON COLUMN tasks.publisher_user_id IS '发布用户编号';
COMMENT ON COLUMN tasks.service_type_id IS '服务类型编号';
COMMENT ON COLUMN tasks.address_no IS '使用地址序号，与 publisher_user_id 共同引用 user_addresses';
COMMENT ON COLUMN tasks.node_id IS '交接节点编号，同时与 service_type_id 共同引用 service_node_rules';
COMMENT ON COLUMN tasks.task_title IS '任务标题';
COMMENT ON COLUMN tasks.task_price IS '任务价格';
COMMENT ON COLUMN tasks.urgent_flag IS '加急标志：Y/N';
COMMENT ON COLUMN tasks.task_status IS '任务状态';
COMMENT ON COLUMN tasks.created_at IS '创建时间，默认 SYSDATE';
COMMENT ON COLUMN tasks.completed_at IS '完成时间';

